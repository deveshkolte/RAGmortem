"""Export a real-data RAGmortem HTML report from the 50-case SQuAD sample."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from pathlib import Path
from typing import Any

os.environ.setdefault("RAGMORTEM_DISABLE_NLI", "1")

REPO_ROOT = Path(__file__).resolve().parent.parent
for path in (REPO_ROOT / "src", REPO_ROOT / "benchmarks"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from ragmortem.cli import evaluate_cases
from ragmortem.report_html import render_html_report
from ragmortem.taxonomy import FailureType
from ragmortem.types import Chunk
from run_real_eval import CATEGORY_TO_EXPECTED_CANONICAL, _build_trace_payloads

DEFAULT_DATA_PATH = REPO_ROOT / "benchmarks" / "data" / "squad_real_world_sample.json"
DEFAULT_OUTPUT_PATH = REPO_ROOT / "docs" / "index.html"


class CaseCorpus:
    """Expose a per-case corpus to the reference-assisted diagnoser."""

    def __init__(self, chunks: list[Chunk]) -> None:
        self.chunks = chunks


def _load_sample(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _case_corpus(
    case: dict[str, Any], passages: dict[str, dict[str, Any]]
) -> CaseCorpus:
    chunks = [
        Chunk(
            id=passage_id,
            text=passages[passage_id]["text"],
            source=passages[passage_id]["title"],
        )
        for passage_id in case["corpus_passage_ids"]
    ]
    return CaseCorpus(chunks)


def _normalized_trace(
    case: dict[str, Any],
    retrieved: list[dict[str, Any]],
    candidates: list[dict[str, Any]],
    top_k: int,
) -> dict[str, Any]:
    return {
        "id": case["id"],
        "query": case["question"],
        "retrieved_chunks": retrieved,
        "candidate_chunks": candidates,
        "top_k": top_k,
        "answer": case["generated_answer"],
        "reference_answer": case["reference_answer"],
        "score_type": "similarity",
    }


def _html_cutoff(cutoff: dict[str, Any] | None) -> dict[str, Any] | None:
    if not cutoff:
        return None
    if "items" in cutoff:
        return {
            "cutoff_k": cutoff.get("cutoff_k", cutoff.get("top_k", 3)),
            "items": cutoff["items"],
        }

    items: list[dict[str, Any]] = []
    for item in cutoff.get("retrieved", []):
        items.append(
            {
                "rank": item.get("rank"),
                "score": item.get("score"),
                "id": item.get("id"),
                "tag": "in_prompt",
            }
        )
    for item in cutoff.get("dropped", []):
        items.append(
            {
                "rank": item.get("rank"),
                "score": item.get("score"),
                "id": item.get("id"),
                "tag": "dropped",
                "gap": abs(float(item.get("gap") or 0.0)),
            }
        )
    return {
        "cutoff_k": cutoff.get("top_k", 3),
        "items": items,
    }


def _summarize(results: list[dict[str, Any]]) -> dict[str, Any]:
    counts = Counter(result["diagnosis"] for result in results)
    unknown_count = counts.get("unknown", 0)
    total_cases = len(results)
    return {
        "total_cases": total_cases,
        "counts_per_diagnosis": dict(counts),
        "unknown_count": unknown_count,
        "unknown_rate_pct": round(unknown_count / total_cases * 100, 1)
        if total_cases
        else 0.0,
    }


def _annotate_provenance(report: str) -> str:
    report = report.replace(
        "Local root-cause failure debugger for Retrieval-Augmented Generation",
        "SQuAD v1.1 real-world evaluation · 50 traces · 16-passage corpora · "
        "deterministic BM25 retrieval · simulated decoy answers",
        1,
    )
    report = report.replace(
        'Report generated by <strong style="color:#f0f6fc;">RAGmortem</strong> •',
        "SQuAD v1.1 dev set (CC BY-SA 4.0) · deterministic BM25 replay · "
        "simulated decoy answers<br>Report generated by "
        '<strong style="color:#f0f6fc;">RAGmortem</strong> •',
        1,
    )
    return "\n".join(line.rstrip() for line in report.splitlines()) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT_PATH)
    parser.add_argument(
        "--profile",
        default="relative",
        choices=("minilm", "openai", "bge", "relative"),
    )
    args = parser.parse_args()

    sample = _load_sample(args.data)
    passages = sample["passages"]
    cases = sample["cases"]

    results: list[dict[str, Any]] = []
    ground_truth_matches = 0
    for case in cases:
        retrieved, candidates, top_k = _build_trace_payloads(case, passages)
        trace = _normalized_trace(case, retrieved, candidates, top_k)
        corpus = _case_corpus(case, passages)
        case_results, _ = evaluate_cases(
            [trace],
            corpus=corpus,
            top_k=top_k,
            mode="corpus_aware",
            profile=args.profile,
        )
        result = case_results[0]
        result["cutoff_info"] = _html_cutoff(result.get("cutoff_info"))
        results.append(result)

        expected = CATEGORY_TO_EXPECTED_CANONICAL[case["category"]]
        predicted = FailureType(result["diagnosis"]).canonical.value
        if predicted == expected:
            ground_truth_matches += 1
        else:
            print(
                f"warning: {case['id']} expected {expected}, got {result['diagnosis']}",
                file=sys.stderr,
            )

    if len(results) != 50:
        raise SystemExit(f"error: expected 50 SQuAD traces, got {len(results)}")

    summary = _summarize(results)
    report = render_html_report(
        results,
        summary,
        is_demo=False,
        profile=args.profile,
    )
    report = _annotate_provenance(report)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")

    print(f"Wrote {args.out} ({args.out.stat().st_size:,} bytes)")
    print(f"Traces: {summary['total_cases']}")
    print(f"Diagnoses: {json.dumps(summary['counts_per_diagnosis'], sort_keys=True)}")
    print(
        f"UNKNOWN: {summary['unknown_count']}/{summary['total_cases']} "
        f"({summary['unknown_rate_pct']}%)"
    )
    print(f"Ground-truth category match: {ground_truth_matches}/{len(results)}")

    if "SYNTHETIC DEMO DATA" in report:
        raise SystemExit("error: synthetic demo banner leaked into report")
    if report.count("squad_rw_") < len(results):
        raise SystemExit("error: report is missing SQuAD trace cards")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
